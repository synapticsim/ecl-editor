import { ECL_VARIABLE } from "../vars";
import type { MsfsSwitchId } from "./switches";

/** One switch's contribution to a test: compares its value, or (with neither
 *  `state` nor `value`) just reads it directly for a bool/truthy test. */
export interface MsfsSwitchRef {
    switch: MsfsSwitchId;
    /** Key into the switch's `states` (Enum switches). */
    state?: string;
    /** Literal comparison value (Number switches, e.g. a lever angle threshold). */
    value?: number;
    /** True if the switch's raw read is the logical inverse of this binding's condition. */
    negate?: boolean;
}

/** A binding is either a single switch reference, or an AND/OR/NOT combinator
 *  over sub-expressions — the same shape whether it's one switch or an
 *  aggregate of several, so every ECL_VARIABLE binding lives in this one
 *  table with no separate override mechanism. */
export type MsfsExpr = MsfsSwitchRef | { op: "AND" | "OR"; args: MsfsExpr[] } | { op: "NOT"; arg: MsfsExpr };

